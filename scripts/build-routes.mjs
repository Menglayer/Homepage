import { readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import '../assets/js/workspace-routes.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const routes = globalThis.WorkspaceRoutes;
const template = (await readFile(path.join(root, 'app.html'), 'utf8')).replace(/\r\n/g, '\n');
const labels = {airdrop:'空投', tools:'工具', register:'注册'};
const descriptions = {
  airdrop:'项目研究与测算工具，放在同一个工作台。',
  tools:'研究、测算与日常操作，按用途找到所需工具。',
  register:'交易所、券商与支付服务，分开查找。'
};

for (const route of routes.paths) {
  const {view} = routes.parse('https://menglayer.cc' + route);
  const file = path.join(root, route.slice(1), 'index.html');
  const html = template
    .replace('<!doctype html>', '<!doctype html>\n<!-- Generated by scripts/build-routes.mjs from app.html. -->')
    .replace(/<title>[^<]*<\/title>/, '<title>' + labels[view] + ' · MengLayer APP</title>')
    .replace(/(<link rel="canonical" href=")[^"]+/, '$1https://menglayer.cc' + route)
    .replace(/(<h1 id="viewTitle" tabindex="-1">)[^<]+/, '$1' + labels[view])
    .replace(/(<p id="viewDescription" class="view-description">)[^<]+/, '$1' + descriptions[view])
    .replace(/ aria-current="page"/g, '')
    .replace('data-view="' + view + '"', 'data-view="' + view + '" aria-current="page"');
  await mkdir(path.dirname(file), {recursive:true});
  await writeFile(file, html);
}

const alias = path.join(root, 'airfrop', 'index.html');
await mkdir(path.dirname(alias), {recursive:true});
await writeFile(alias, '<!doctype html>\n<html lang="zh-CN"><head><meta charset="utf-8"><title>空投 · MengLayer APP</title><link rel="canonical" href="https://menglayer.cc/airdrop/"><meta name="robots" content="noindex, follow"><meta http-equiv="refresh" content="0;url=/airdrop/"></head><body><a href="/airdrop/">打开空投 / Open Airdrops</a></body></html>\n');

const urls = ['/', ...routes.paths].map(route => `  <url><loc>https://menglayer.cc${route}</loc><changefreq>weekly</changefreq><priority>${route === '/' ? '1.0' : '0.8'}</priority></url>`);
await writeFile(path.join(root, 'sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + urls.join('\n') + '\n</urlset>\n');
console.log(JSON.stringify({pages:routes.paths.length, alias:'/airfrop/', sitemap:urls.length}));
